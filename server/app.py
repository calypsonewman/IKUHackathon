"""Travel Health Map server.

Serves the static app and a /api/news endpoint that asks Gemini (with Google Search grounding)
for recent travel-relevant news about a country. Results are cached on disk per country.
Standard library only, so it runs with `python3 server/app.py` and nothing to install.

Later: swap the file cache in `NewsCache` for Tiger Cloud (Postgres/TimescaleDB).
"""
import json
import os
import re
import threading
import time
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from email.utils import parsedate_to_datetime
from datetime import date
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, quote_plus, urlencode, urlparse

ROOT = Path(__file__).resolve().parent.parent
SERVER_DIR = ROOT / "server"
CACHE_DIR = SERVER_DIR / "cache"
CACHE_TTL_SECONDS = 12 * 60 * 60
CATEGORIES = {"outbreak", "safety", "entry", "weather", "other"}


def load_env(path):
    if not path.exists():
        return
    for line in path.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            os.environ.setdefault(key.strip(), value.strip())


load_env(SERVER_DIR / ".env")
API_KEY = os.environ.get("GEMINI_API_KEY", "")
MODEL = os.environ.get("GEMINI_MODEL", "gemini-3.8-flash")
# Used when the main model is overloaded. A different model family usually has spare capacity.
FALLBACK_MODEL = os.environ.get("GEMINI_FALLBACK_MODEL", "gemini-3.5-flash")
gemini_used = threading.local()
PORT = int(os.environ.get("PORT", "8000"))
# auto = try Google Search grounding, fall back to Google News RSS + Gemini summary
NEWS_MODE = os.environ.get("NEWS_MODE", "auto")
grounding_blocked_until = 0.0


class GeminiError(Exception):
    def __init__(self, message, status=None):
        super().__init__(message)
        self.status = status


PROMPT = """Today is {today}. Search recent local and international news (last 14 days) about {country}
that matters to UK travellers: disease outbreaks, natural disasters or severe weather, unrest or
security incidents, strikes or transport disruption, and changes to entry rules.

Respond with JSON only (no markdown), in this exact shape:
[{{"category": "outbreak|safety|entry|weather|other", "severity": 1, "headline": "...",
   "summary": "...", "event_date": "YYYY-MM-DD"}}]
- severity: 1 = minor/background, 2 = notable, 3 = serious/urgent
- summary: at most 2 short factual sentences, no medical advice
- at most 6 items, most important first
- return [] if there is nothing significant. Never invent events."""


def call_gemini(body):
    """Try the main model, then the fallback if Google says it's overloaded (503) or rate-limited (429)."""
    if not API_KEY:
        raise GeminiError("GEMINI_API_KEY is not set in server/.env")
    models = [MODEL] + ([FALLBACK_MODEL] if FALLBACK_MODEL and FALLBACK_MODEL != MODEL else [])
    attempts = [(m, 0) for m in models] + [(m, 3) for m in models]  # second round after a short pause
    for i, (model, pause) in enumerate(attempts):
        time.sleep(pause if model == models[0] else 0)
        try:
            result = call_model(model, body)
            gemini_used.model = model  # remembered per request thread, for the "generated by" note
            return result
        except GeminiError as err:
            if err.status not in (429, 503) or i == len(attempts) - 1:
                raise


def call_model(model, body):
    req = urllib.request.Request(
        f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json", "x-goog-api-key": API_KEY},
    )
    try:
        with urllib.request.urlopen(req, timeout=90) as resp:
            data = json.load(resp)
    except urllib.error.HTTPError as err:
        try:
            message = json.load(err)["error"]["message"]
        except Exception:
            message = str(err)
        raise GeminiError(f"Gemini API error {err.code}: {message}", err.code)
    except urllib.error.URLError as err:
        raise GeminiError(f"Could not reach Gemini: {err.reason}")
    candidate = (data.get("candidates") or [{}])[0]
    text = "".join(p.get("text", "") for p in candidate.get("content", {}).get("parts", []))
    return text, candidate


def news_grounded(country):
    """Gemini searches the web itself (needs Search grounding quota)."""
    body = {
        "contents": [{"parts": [{"text": PROMPT.format(today=date.today().isoformat(), country=country)}]}],
        "tools": [{"google_search": {}}],
    }
    text, candidate = call_gemini(body)
    sources = []
    for chunk in candidate.get("groundingMetadata", {}).get("groundingChunks", []):
        web = chunk.get("web") or {}
        source = {"title": web.get("title") or "Source", "uri": web.get("uri", "")}
        if source["uri"].startswith("https://") and source not in sources:
            sources.append(source)
    return parse_items(text), sources[:10], "Google Search grounding"


RSS_TERMS = "(outbreak OR disease OR travel OR tourists OR protest OR unrest OR flood OR earthquake OR storm OR strike OR visa)"


def fetch_headlines(country, limit=25):
    url = ("https://news.google.com/rss/search?q=" + quote_plus(f'"{country}" {RSS_TERMS} when:14d')
           + "&hl=en-GB&gl=GB&ceid=GB:en")
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "TravelHealthMap/1.0"}), timeout=20) as resp:
            root = ET.fromstring(resp.read())
    except Exception as err:
        raise GeminiError(f"Could not fetch news feed: {err}")
    headlines = []
    for item in root.findall(".//item"):
        try:
            published = parsedate_to_datetime(item.findtext("pubDate"))
        except Exception:
            continue
        link = item.findtext("link") or ""
        if link.startswith("https://"):
            headlines.append({"title": item.findtext("title") or "", "source": item.findtext("source") or "",
                              "date": published, "link": link})
    headlines.sort(key=lambda h: h["date"], reverse=True)
    return headlines[:limit]


RSS_PROMPT = """Today is {today}. Below are recent news headlines about {country}, numbered.
Using ONLY these headlines, pick the ones that matter to UK travellers (disease outbreaks, natural disasters
or severe weather, unrest or security incidents, strikes or transport disruption, entry-rule changes).
Merge headlines about the same event. Ignore sport, business and politics with no traveller impact.

Return a JSON list (at most 6 items, most important first):
[{{"category": "outbreak|safety|entry|weather|other", "severity": 1, "headline": "...",
   "summary": "...", "event_date": "YYYY-MM-DD", "sources": [1, 4]}}]
- severity: 1 = minor/background, 2 = notable, 3 = serious/urgent
- summary: at most 2 short factual sentences based only on the headlines, no medical advice
- sources: the headline numbers you used
- return [] if nothing is relevant. Never add facts that are not in the headlines.

Headlines:
{headlines}"""


def news_from_rss(country):
    """Free-tier path: real headlines from Google News, summarised by Gemini without web access."""
    headlines = fetch_headlines(country)
    if not headlines:
        return [], [], "Google News"
    listing = "\n".join(f"{i}. [{h['date']:%Y-%m-%d}] {h['title']}" for i, h in enumerate(headlines, 1))
    body = {
        "contents": [{"parts": [{"text": RSS_PROMPT.format(today=date.today().isoformat(), country=country, headlines=listing)}]}],
        "generationConfig": {"responseMimeType": "application/json"},
    }
    text, _ = call_gemini(body)
    items = parse_items(text)
    used = []
    for item in items:
        refs = [headlines[n - 1] for n in item.pop("source_ids", []) if 1 <= n <= len(headlines)]
        item["sources"] = [{"title": h["source"] or "Source", "uri": h["link"]} for h in refs]
        used += [s for s in item["sources"] if s not in used]
    return items, used, "Google News"


def ask_gemini(country):
    global grounding_blocked_until
    if NEWS_MODE == "rss":
        return news_from_rss(country)
    if NEWS_MODE == "auto" and time.time() < grounding_blocked_until:
        return news_from_rss(country)
    try:
        return news_grounded(country)
    except GeminiError as err:
        # 429/403 here usually means Search grounding isn't available on this key's plan.
        if NEWS_MODE == "auto" and err.status in (403, 429):
            grounding_blocked_until = time.time() + 3600
            return news_from_rss(country)
        raise


def parse_items(text):
    """Pull the JSON list out of the model's reply and validate every field."""
    start, end = text.find("["), text.rfind("]")
    if start == -1 or end < start:
        raise GeminiError("Gemini did not return a news list")
    try:
        raw = json.loads(text[start : end + 1])
    except json.JSONDecodeError:
        raise GeminiError("Gemini returned malformed JSON")

    items = []
    for item in raw if isinstance(raw, list) else []:
        if not isinstance(item, dict) or not item.get("headline"):
            continue
        category = str(item.get("category", "other")).lower()
        try:
            severity = min(3, max(1, int(item.get("severity", 1))))
        except (TypeError, ValueError):
            severity = 1
        event_date = str(item.get("event_date", ""))
        items.append({
            "category": category if category in CATEGORIES else "other",
            "severity": severity,
            "headline": str(item["headline"])[:200],
            "summary": str(item.get("summary", ""))[:500],
            "event_date": event_date if re.fullmatch(r"\d{4}-\d{2}-\d{2}", event_date) else "",
            "source_ids": [n for n in item.get("sources", []) if isinstance(n, int)][:5],
        })
    items = items[:6]
    return items


def build_news(country):
    items, sources, method = ask_gemini(country)
    for item in items:
        item.pop("source_ids", None)
    return {
        "country": country,
        "updated": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "model": getattr(gemini_used, "model", MODEL),
        "method": method,
        "items": items,
        "sources": sources,
    }


# ---------- NHS Directory of Healthcare Services (clinics) ----------

NHS_API_KEY = os.environ.get("NHS_API_KEY", "")
# Integration test environment: a close copy of live NHS data, free self-service key.
NHS_API_BASE = os.environ.get("NHS_API_BASE", "https://int.api.service.nhs.uk/service-search-api/")
CLINIC_CACHE_TTL_SECONDS = 24 * 60 * 60
# "Travel clinic" is the code pharmacies actually use. The documented SRV0302/SRV0303 codes return nothing.
TRAVEL_CLINIC_CODE = "SRV0516"
NHS_FIELDS = "ODSCode,OrganisationName,OrganisationTypeId,Address1,Address2,Address3,City,Postcode,Latitude,Longitude,Contacts,OpeningTimes,Services"
nhs_lock = threading.Lock()
nhs_last_call = 0.0


class NhsError(Exception):
    pass


def nhs_search(filter_expr, lat, lng, top):
    """Nearest organisations matching an OData filter, closest first."""
    global nhs_last_call
    if not NHS_API_KEY:
        raise NhsError("NHS_API_KEY is not set in server/.env")
    params = {
        "api-version": "3",
        "search": "*",
        "$filter": filter_expr,
        "$orderby": f"geo.distance(Geocode, geography'POINT({lng} {lat})')",  # note: longitude first
        "$top": str(top),
        "$select": NHS_FIELDS,
    }
    req = urllib.request.Request(NHS_API_BASE + "?" + urlencode(params), headers={"apikey": NHS_API_KEY})
    with nhs_lock:  # the integration environment allows 1 request per second
        wait = nhs_last_call + 1.1 - time.time()
        if wait > 0:
            time.sleep(wait)
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                return json.load(resp).get("value", [])
        except urllib.error.HTTPError as err:
            raise NhsError(f"NHS API error {err.code}")
        except urllib.error.URLError as err:
            raise NhsError(f"Could not reach the NHS API: {err.reason}")
        finally:
            nhs_last_call = time.time()


def simplify_org(org):
    """Keep only what the browser needs, in a flat, predictable shape."""
    contacts = {c.get("ContactMethodType"): c.get("ContactValue") for c in org.get("Contacts") or []}
    website = (contacts.get("Website") or "").strip()
    if website and not website.startswith(("http://", "https://")):
        website = "https://" + website
    hours = {}
    for t in org.get("OpeningTimes") or []:
        if t.get("OpeningTimeType") == "General" and t.get("IsOpen"):
            hours.setdefault(t["Weekday"], []).append([t["OpeningTime"], t["ClosingTime"]])
    name = (org.get("OrganisationName") or "Unnamed").strip()
    lines = [(org.get(k) or "").strip() for k in ("Address1", "Address2", "Address3", "City")]  # some lines are just spaces
    return {
        "id": org.get("ODSCode"),
        "name": name,
        "kind": "gp" if org.get("OrganisationTypeId") == "GPB" else "pharmacy",
        "address": ", ".join(x for x in lines if x and x != name),
        "postcode": org.get("Postcode") or "",
        "lat": org.get("Latitude"),
        "lng": org.get("Longitude"),
        "phone": contacts.get("Telephone") or "",
        "website": website,
        "travelClinic": any(s.get("ServiceCode") == TRAVEL_CLINIC_CODE for s in org.get("Services") or []),
        "hours": hours,
    }


def find_clinics(lat, lng):
    pharmacies = nhs_search(f"Services/any(s: s/ServiceCode eq '{TRAVEL_CLINIC_CODE}')", lat, lng, 15)
    gps = nhs_search("OrganisationTypeId eq 'GPB'", lat, lng, 5)
    return {
        "updated": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "source": "NHS Directory of Healthcare Services" + (" (test environment)" if "int." in NHS_API_BASE else ""),
        "clinics": [simplify_org(o) for o in pharmacies + gps if o.get("Latitude") is not None],
    }


class FileCache:
    """One JSON file per key, reused until it is older than `ttl` seconds. Replace with Tiger Cloud later."""

    def __init__(self):
        CACHE_DIR.mkdir(exist_ok=True)
        self.locks = {}
        self.guard = threading.Lock()

    def lock_for(self, key):
        with self.guard:
            return self.locks.setdefault(key, threading.Lock())

    def get(self, key, ttl, compute):
        path = CACHE_DIR / f"{key}.json"
        with self.lock_for(key):  # one outside call per key at a time
            if path.exists() and time.time() - path.stat().st_mtime < ttl:
                return json.loads(path.read_text())
            result = compute()
            path.write_text(json.dumps(result, indent=2))
            return result


cache = FileCache()


class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT), **kwargs)

    def end_headers(self):
        # Make the browser re-check files on every load, so code changes show up straight away.
        self.send_header("Cache-Control", "no-cache")
        super().end_headers()

    def send_json(self, status, payload):
        body = json.dumps(payload).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        url = urlparse(self.path)
        # Never serve the server folder (it holds .env), git data or dotfiles.
        if url.path.startswith(("/server", "/.")) or "/." in url.path:
            return self.send_error(404)
        if url.path == "/api/news":
            return self.news(parse_qs(url.query))
        if url.path == "/api/clinics":
            return self.clinics(parse_qs(url.query))
        return super().do_GET()

    def news(self, query):
        code = (query.get("code") or [""])[0]
        country = (query.get("country") or [""])[0].strip()
        if not re.fullmatch(r"[A-Za-z0-9]{1,4}", code) or not re.fullmatch(r"[\w .,'&()\-]{2,60}", country):
            return self.send_json(400, {"error": "Invalid country"})
        try:
            self.send_json(200, cache.get(f"news-{code}", CACHE_TTL_SECONDS, lambda: build_news(country)))
        except GeminiError as err:
            self.log_message("news error for %s: %s", country, err)
            busy = err.status in (429, 503)
            self.send_json(502, {"error": "the AI news service is busy right now. Please try again in a few minutes." if busy else str(err)})

    def clinics(self, query):
        try:
            lat, lng = float(query["lat"][0]), float(query["lng"][0])
        except (KeyError, ValueError):
            return self.send_json(400, {"error": "lat and lng are required"})
        if not (49.8 <= lat <= 61 and -8.7 <= lng <= 2):
            return self.send_json(400, {"error": "The NHS directory only covers the UK. Enter a UK postcode or town."})
        # Round to ~1 km so nearby searches share a cache entry (saves our 1,500 requests/week).
        # The browser works out exact distances from the user's real position.
        lat, lng = round(lat, 2), round(lng, 2)
        try:
            self.send_json(200, cache.get(f"clinics-{lat}_{lng}", CLINIC_CACHE_TTL_SECONDS, lambda: find_clinics(lat, lng)))
        except NhsError as err:
            self.log_message("clinics error at %s,%s: %s", lat, lng, err)
            self.send_json(502, {"error": str(err)})


if __name__ == "__main__":
    print(f"Travel Health Map on http://localhost:{PORT}  (Gemini model: {MODEL}, news mode: {NEWS_MODE}, key {'set' if API_KEY else 'MISSING'}, NHS key {'set' if NHS_API_KEY else 'MISSING'})")
    ThreadingHTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
