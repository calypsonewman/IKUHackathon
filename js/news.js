// "Latest news" section: AI summaries (Gemini + Google Search) fetched from server/app.py.
const News = (() => {
  const memo = {}; // code -> Promise of result, so reopening doesn't refetch
  const SEVERITY = { 1: ['', 'Background'], 2: ['warn', 'Notable'], 3: ['danger', 'Serious'] };
  const CATEGORY = { outbreak: '🦠 Outbreak', safety: '⚠️ Safety', entry: '🛂 Entry rules', weather: '🌪️ Weather', other: '📰 News' };

  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const fmtDate = (d) => (d ? new Date(d).toLocaleDateString('en-GB', { day: 'numeric', month: 'short' }) : '');

  async function fetchNews(country) {
    const url = `/api/news?code=${encodeURIComponent(country.code)}&country=${encodeURIComponent(country.name)}`;
    const res = await fetch(url);
    if (res.status === 404) throw new Error('News needs the app server. Start it with: python3 server/app.py');
    const data = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(data.error || `Server error ${res.status}`);
    return data;
  }

  function render(data) {
    const items = data.items.length
      ? data.items.map((it) => {
          const [cls, label] = SEVERITY[it.severity] || SEVERITY[1];
          return `<div class="news-item sev-${it.severity}">
            <div class="news-meta"><span>${CATEGORY[it.category] || CATEGORY.other}</span>
              <span class="badge ${cls}">${label}</span>${it.event_date ? `<span>${fmtDate(it.event_date)}</span>` : ''}</div>
            <p class="news-headline">${esc(it.headline)}</p>
            <p class="news-summary">${esc(it.summary)}</p>
            ${it.sources?.length ? `<p class="news-src">${it.sources.map((x) =>
              `<a href="${esc(x.uri)}" target="_blank" rel="noopener">${esc(x.title)} ↗</a>`).join(' · ')}</p>` : ''}
          </div>`;
        }).join('')
      : '<p>No significant travel-related news found in the last 14 days.</p>';
    const perItem = data.items.some((it) => it.sources?.length);
    const sources = data.sources.length && !perItem
      ? `<p class="small"><strong>Sources:</strong> ${data.sources.map((s) =>
          `<a href="${esc(s.uri)}" target="_blank" rel="noopener">${esc(s.title)}</a>`).join(' · ')}</p>`
      : '';
    return `${items}${sources}
      <p class="ai-note">🤖 AI summary of news found via ${esc(data.method || 'Google Search')}, generated by ${esc(data.model)} on
        ${new Date(data.updated).toLocaleString('en-GB', { dateStyle: 'medium', timeStyle: 'short' })}.
        It may be inaccurate or incomplete: check the sources and the official FCDO advice. It does not change the vaccine advice above.</p>`;
  }

  // Load into `container` the first time its <details> is opened.
  function attach(details, container, country) {
    const load = () => {
      if (!details.open || container.dataset.loaded) return;
      container.dataset.loaded = '1';
      container.innerHTML = '<p class="loading">Searching recent news… this can take up to 30 seconds.</p>';
      memo[country.code] = memo[country.code] || fetchNews(country);
      memo[country.code]
        .then((data) => { container.innerHTML = render(data); })
        .catch((err) => {
          delete memo[country.code];
          delete container.dataset.loaded;
          container.innerHTML = `<p class="error">Couldn't load news: ${esc(err.message)}</p>`;
        });
    };
    details.addEventListener('toggle', load);
    load();
  }

  return { attach };
})();
